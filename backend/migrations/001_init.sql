-- The first schema: orders with their items and history, plus the stores that make retries safe
-- (Idempotency-Key responses, courier webhook event ids) and the webhook log.
--
-- Allowed values are text columns with a CHECK instead of PostgreSQL ENUM types: adding a value later is a
-- one-line migration (drop and re-create the CHECK), while an ENUM value can't be removed or renamed easily.
-- The lists must match the TypeScript constants; tests/integration/schema.test.ts checks every value.

CREATE TABLE orders (
  id uuid PRIMARY KEY,
  -- The human-readable number "ORD-1001". BY DEFAULT (not ALWAYS) so the demo seed can insert its own
  -- numbers in a fixed order; new orders take the next value from the identity sequence.
  order_seq bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) UNIQUE,
  customer_name text NOT NULL,
  customer_email text NOT NULL,
  delivery_address text NOT NULL,
  destination_city text NOT NULL,
  postal_code text NOT NULL,
  destination_country text NOT NULL CHECK (destination_country ~ '^[A-Z]{2}$'),
  -- The same type as a JavaScript number, so any weight the API accepted comes back unchanged.
  parcel_weight_kg double precision NOT NULL CHECK (parcel_weight_kg > 0 AND parcel_weight_kg <= 100),
  -- bigint: 50 items × 999 × €100,000 doesn't fit into a 32-bit integer of cents.
  total_cents bigint NOT NULL CHECK (total_cents >= 0),
  currency text NOT NULL CHECK (currency = 'EUR'),
  payment_status text NOT NULL CHECK (payment_status IN ('PAID', 'UNPAID', 'REFUNDED')),
  courier_provider text,
  status text NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'SHIPPED', 'IN_TRANSIT', 'DELIVERED', 'FAILED', 'CANCELLED', 'RETURNED')),
  -- UNIQUE allows many NULLs (orders not shipped yet), but never the same courier number twice.
  tracking_number text UNIQUE,
  -- Set while a ship request is talking to the courier: the lock that stops a second shipment, across
  -- any number of server processes. Separate from the status: PROCESSING means "being prepared".
  shipping_started_at timestamptz,
  shipping_provider_id text,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  CONSTRAINT orders_shipping_marker_complete CHECK ((shipping_started_at IS NULL) = (shipping_provider_id IS NULL))
);

-- The list: newest first, with the order number breaking ties (GET /api/orders, ORDER BY ... LIMIT).
CREATE INDEX orders_created_at_idx ON orders (created_at DESC, order_seq DESC);
-- The status filter.
CREATE INDEX orders_status_idx ON orders (status);
-- The recovery job looks only for shipments in flight: a partial index stays tiny (almost always empty).
CREATE INDEX orders_shipping_started_at_idx ON orders (shipping_started_at) WHERE shipping_started_at IS NOT NULL;

CREATE TABLE order_items (
  -- An item can't exist without its order; deleting an order deletes its items.
  order_id uuid NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  position smallint NOT NULL CHECK (position >= 0), -- keeps the items in the order they were entered
  sku text NOT NULL,
  name text NOT NULL,
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price_cents integer NOT NULL CHECK (unit_price_cents > 0),
  PRIMARY KEY (order_id, position) -- also the index for "all items of these orders"
);

CREATE TABLE order_events (
  id uuid PRIMARY KEY,
  -- Insertion order: breaks ties between events written in the same millisecond.
  seq bigint GENERATED ALWAYS AS IDENTITY,
  -- No ON DELETE CASCADE: the history is an audit log, an order with history can't silently disappear.
  order_id uuid NOT NULL REFERENCES orders (id),
  type text NOT NULL CHECK (type IN ('ORDER_CREATED', 'STATUS_CHANGED', 'SHIPMENT_CREATED', 'SHIPMENT_REJECTED', 'PROVIDER_UNAVAILABLE', 'PROVIDER_TIMEOUT', 'PAYMENT_RECORDED', 'WEBHOOK_IGNORED')),
  from_status text CHECK (from_status IN ('PENDING', 'PROCESSING', 'SHIPPED', 'IN_TRANSIT', 'DELIVERED', 'FAILED', 'CANCELLED', 'RETURNED')),
  to_status text NOT NULL CHECK (to_status IN ('PENDING', 'PROCESSING', 'SHIPPED', 'IN_TRANSIT', 'DELIVERED', 'FAILED', 'CANCELLED', 'RETURNED')),
  source text NOT NULL CHECK (source IN ('api', 'provider', 'webhook', 'system')),
  message text NOT NULL,
  provider_id text,
  code text,
  attempts integer CHECK (attempts >= 1),
  created_at timestamptz NOT NULL,
  -- Only the first event of an order has no previous status.
  CONSTRAINT order_events_from_status_only_on_create CHECK ((type = 'ORDER_CREATED') = (from_status IS NULL))
);

-- One order's history, oldest first.
CREATE INDEX order_events_order_idx ON order_events (order_id, created_at, seq);
-- Recent events across all orders (Integrations page, "Updated today").
CREATE INDEX order_events_created_at_idx ON order_events (created_at DESC, seq DESC);

-- Responses remembered per Idempotency-Key (24 h), so a retried POST gets the same answer.
CREATE TABLE idempotency_keys (
  key text PRIMARY KEY, -- the claim: INSERT ... ON CONFLICT DO NOTHING lets exactly one request own a key
  fingerprint text NOT NULL, -- sha256 of method, path and body
  state text NOT NULL CHECK (state IN ('in_flight', 'done')),
  response_status integer,
  response_body jsonb,
  response_location text,
  created_at timestamptz NOT NULL,
  -- While in flight: after this moment the owner is presumed dead (crashed process) and the key can be taken over.
  locked_until timestamptz,
  CONSTRAINT idempotency_keys_response_when_done CHECK ((state = 'done') = (response_status IS NOT NULL))
);
CREATE INDEX idempotency_keys_created_at_idx ON idempotency_keys (created_at); -- cleanup of expired keys

-- Courier webhook events already handled (7 days), so a redelivered event changes nothing.
CREATE TABLE webhook_events (
  provider_id text NOT NULL,
  event_id text NOT NULL,
  state text NOT NULL CHECK (state IN ('in_flight', 'kept')),
  claimed_at timestamptz NOT NULL,
  locked_until timestamptz,
  PRIMARY KEY (provider_id, event_id) -- event ids are only unique per courier
);
CREATE INDEX webhook_events_claimed_at_idx ON webhook_events (claimed_at); -- cleanup of expired claims

-- Every webhook request and what we did with it, including the refused ones.
CREATE TABLE webhook_receipts (
  id uuid PRIMARY KEY,
  seq bigint GENERATED ALWAYS AS IDENTITY,
  received_at timestamptz NOT NULL,
  provider_id text NOT NULL,
  outcome text NOT NULL CHECK (outcome IN ('accepted', 'duplicate', 'unchanged', 'ignored_transition', 'unmapped_status', 'unknown_tracking', 'invalid_signature', 'stale', 'invalid_payload', 'not_configured')),
  request_id text,
  -- Body fields only for requests whose signature checked out (see webhookLog.ts).
  event_id text,
  tracking_number text,
  external_status text,
  status text CHECK (status IN ('PENDING', 'PROCESSING', 'SHIPPED', 'IN_TRANSIT', 'DELIVERED', 'FAILED', 'CANCELLED', 'RETURNED')),
  order_id uuid REFERENCES orders (id)
);
CREATE INDEX webhook_receipts_received_at_idx ON webhook_receipts (received_at DESC, seq DESC);
